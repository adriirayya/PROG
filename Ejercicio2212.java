public class Ejercicio2212 {
    public static void main(String[] args) {
        int penaldo = 13;
        int pessi = 5;
        System.out.println("El resultado es: " + penaldo/pessi);

        double penaldo2 = 13;
        double pessi2 = 5;
        System.out.println("El resultado es: " + penaldo2/pessi2);

        System.out.println("El resultado cambia es en las decimales, al utilizar double, el resultado es mas preciso.");
    }
}